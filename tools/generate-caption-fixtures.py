"""Generate ten original, silent videos with real embedded subtitle tracks.

Run from any directory: python tools/generate-caption-fixtures.py
Requires FFmpeg and FFprobe on PATH (or C:/ffmpeg/bin on Windows). The ZIP is
androidTest-only; all video/audio is generated by FFmpeg's lavfi sources.
"""
from pathlib import Path
import json
import shutil
import subprocess
import tempfile
import zipfile


REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "app/src/androidTest/assets/caption-fixtures.zip"
DURATION_SECONDS = 8
END_MS = 7_000


def binary(name):
    located = shutil.which(name)
    fallback = Path("C:/ffmpeg/bin") / f"{name}.exe"
    if located:
        return located
    if fallback.is_file():
        return str(fallback)
    raise SystemExit(f"{name} is required to regenerate caption fixtures")


def track(language, token, text, default=True, forced=False):
    return dict(language=language, token=token, text=text, default=default, forced=forced)


CASES = [
    dict(name="case01-movtext-en.mp4", codec="mov_text", firstCueMs=500,
         tracks=[track("eng", "Case01", "Case01 English caption")]),
    dict(name="case02-movtext-hi.mp4", codec="mov_text", firstCueMs=500,
         tracks=[track("hin", "Case02", "Case02 हिन्दी उपशीर्षक")]),
    dict(name="case03-subrip-ar.mkv", codec="srt", firstCueMs=500,
         tracks=[track("ara", "Case03", "Case03 ترجمة عربية")]),
    dict(name="case04-subrip-es.mkv", codec="srt", firstCueMs=500,
         tracks=[track("spa", "Case04", "Case04 Subtítulo español")]),
    dict(name="case05-ass-ja.mkv", codec="ass", firstCueMs=500,
         tracks=[track("jpn", "Case05", "Case05 日本語の字幕")]),
    dict(name="case06-ass-styled-en.mkv", codec="ass", firstCueMs=500,
         tracks=[track("eng", "Case06", "Case06 Styled Latin caption")], styled=True),
    dict(name="case07-multi-en-fr.mkv", codec="srt", firstCueMs=500,
         tracks=[track("eng", "Case07", "Case07 English dialogue"),
                 track("fra", "Case07FR", "Case07FR Sous-titre français", default=False)]),
    dict(name="case08-forced-en.mkv", codec="srt", firstCueMs=500,
         tracks=[track("eng", "Case08", "Case08 Forced English caption", default=False, forced=True)]),
    dict(name="case09-nondefault-en.mkv", codec="srt", firstCueMs=500,
         tracks=[track("eng", "Case09", "Case09 Nondefault English caption", default=False)]),
    dict(name="case10-delayed-multiline-en.mkv", codec="srt", firstCueMs=2_000,
         tracks=[track("eng", "Case10", "Case10 <i>Line one</i>\nLine two &amp; entities.")],
         expectedText="Case10 Line one\nLine two & entities."),
]


def timestamp(millis, ass=False):
    hours, remainder = divmod(millis, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    seconds, fraction = divmod(remainder, 1_000)
    if ass:
        return f"{hours}:{minutes:02}:{seconds:02}.{fraction // 10:02}"
    return f"{hours:02}:{minutes:02}:{seconds:02},{fraction:03}"


def write_subtitle(path, case, subtitle):
    start = timestamp(case["firstCueMs"], ass=case["codec"] == "ass")
    end = timestamp(END_MS, ass=case["codec"] == "ass")
    if case["codec"] != "ass":
        content = f"1\n{start} --> {end}\n{subtitle['text']}\n"
    else:
        color = "&H0000FFFF" if case.get("styled") else "&H00FFFFFF"
        italic = -1 if case.get("styled") else 0
        content = (
            "[Script Info]\nScriptType: v4.00+\nPlayResX: 320\nPlayResY: 180\n\n"
            "[V4+ Styles]\n"
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
            "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
            "Alignment, MarginL, MarginR, MarginV, Encoding\n"
            f"Style: Default,Arial,18,{color},&H000000FF,&H00000000,&H80000000,0,{italic},0,0,"
            "100,100,0,0,1,1,0,2,8,8,12,1\n\n"
            "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
            f"Dialogue: 0,{start},{end},Default,,0,0,0,,{subtitle['text']}\n"
        )
    path.write_text(content, encoding="utf-8")


def run(ffmpeg, *arguments):
    subprocess.run([ffmpeg, "-y", "-hide_banner", "-loglevel", "error", *arguments], check=True)


def verify(ffmpeg, ffprobe, path, case):
    result = subprocess.run(
        [ffprobe, "-v", "error", "-show_streams", "-show_format", "-of", "json", str(path)],
        capture_output=True, text=True, encoding="utf-8", check=True,
    )
    probe = json.loads(result.stdout)
    video = [stream for stream in probe["streams"] if stream["codec_type"] == "video"]
    audio = [stream for stream in probe["streams"] if stream["codec_type"] == "audio"]
    subtitles = [stream for stream in probe["streams"] if stream["codec_type"] == "subtitle"]
    assert len(video) == 1 and video[0]["codec_name"] == "h264", path.name
    assert (video[0]["width"], video[0]["height"]) == (320, 180), path.name
    assert len(audio) == 1 and audio[0]["codec_name"] == "aac", path.name
    assert 7.9 <= float(probe["format"]["duration"]) <= 8.1, path.name
    assert len(subtitles) == len(case["tracks"]), path.name
    for index, (stream, subtitle) in enumerate(zip(subtitles, case["tracks"])):
        assert stream["codec_name"] == {"srt": "subrip"}.get(case["codec"], case["codec"]), path.name
        assert stream["tags"]["language"] == subtitle["language"], path.name
        assert bool(stream["disposition"]["default"]) == subtitle["default"], path.name
        assert bool(stream["disposition"]["forced"]) == subtitle["forced"], path.name
        decoded = subprocess.run(
            [ffmpeg, "-v", "error", "-copyts", "-i", str(path), "-map", f"0:s:{index}", "-c:s", "srt", "-f", "srt", "-"],
            capture_output=True, check=True,
        ).stdout.decode("utf-8")
        assert subtitle["token"] in decoded, path.name
        expected_timing = f"{timestamp(case['firstCueMs'])} --> {timestamp(END_MS)}"
        assert expected_timing in decoded, (path.name, expected_timing)


def main():
    ffmpeg, ffprobe = binary("ffmpeg"), binary("ffprobe")
    build = REPO / "build"
    build.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="caption-fixtures-", dir=build) as temporary:
        root = Path(temporary)
        manifest = dict(version=1, cases=[])
        for index, case in enumerate(CASES):
            arguments = [
                "-fflags", "+bitexact", "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=24",
                "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo",
            ]
            for track_index, subtitle in enumerate(case["tracks"]):
                extension = "ass" if case["codec"] == "ass" else "srt"
                source = root / f"source-{index}-{track_index}.{extension}"
                write_subtitle(source, case, subtitle)
                arguments += ["-i", str(source)]
            arguments += ["-map", "0:v:0", "-map", "1:a:0"]
            for track_index in range(len(case["tracks"])):
                arguments += ["-map", f"{track_index + 2}:s:0"]
            arguments += [
                "-t", str(DURATION_SECONDS), "-vf", f"hue=h={index * 23}",
                "-c:v", "libx264", "-preset", "ultrafast", "-crf", "30", "-g", "24",
                "-pix_fmt", "yuv420p", "-threads", "1", "-flags:v", "+bitexact",
                "-c:a", "aac", "-b:a", "32k", "-flags:a", "+bitexact", "-c:s", case["codec"],
                "-avoid_negative_ts", "disabled",
                "-metadata", f"title=NikTV original caption fixture Case{index + 1:02}",
                "-metadata:s:a:0", "language=eng", "-fflags", "+bitexact",
            ]
            for track_index, subtitle in enumerate(case["tracks"]):
                disposition = "+".join(key for key in ("default", "forced") if subtitle[key]) or "0"
                arguments += [
                    f"-metadata:s:s:{track_index}", f"language={subtitle['language']}",
                    f"-metadata:s:s:{track_index}", f"title={subtitle['token']} {subtitle['language']}",
                    f"-disposition:s:{track_index}", disposition,
                ]
            if case["name"].endswith(".mp4"):
                arguments += ["-movflags", "+faststart"]
            target = root / case["name"]
            run(ffmpeg, *arguments, str(target))
            verify(ffmpeg, ffprobe, target, case)
            first = case["tracks"][0]
            manifest["cases"].append(dict(
                name=target.name,
                mime="video/mp4" if target.suffix == ".mp4" else "video/x-matroska",
                expectedToken=first["token"], language=first["language"],
                subtitleCount=len(case["tracks"]), firstCueMs=case["firstCueMs"], endCueMs=END_MS,
                expectedText=case.get("expectedText", first["text"]),
                tracks=case["tracks"],
            ))
            print(f"Verified {target.name}: {len(case['tracks'])} embedded subtitle track(s)")
        (root / "metadata.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
        )
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        temporary_zip = root / "caption-fixtures.zip"
        with zipfile.ZipFile(temporary_zip, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for name in sorted([case["name"] for case in CASES] + ["metadata.json"]):
                info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.create_system = 3
                info.external_attr = 0o100644 << 16
                archive.writestr(info, (root / name).read_bytes(), compresslevel=9)
        assert temporary_zip.stat().st_size < 10_000_000, "Keep the androidTest asset below 10 MB"
        temporary_zip.replace(OUTPUT)
        print(f"Generated {OUTPUT.relative_to(REPO)} ({OUTPUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
