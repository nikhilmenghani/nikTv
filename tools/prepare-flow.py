from pathlib import Path
import copy
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
FLOW = ROOT / "niktube-flow"
ANDROID = "http://schemas.android.com/apk/res/android"
TOOLS = "http://schemas.android.com/tools"
ET.register_namespace("android", ANDROID)
ET.register_namespace("tools", TOOLS)
manifest = ET.parse(FLOW / "app/src/main/AndroidManifest.xml")
application = manifest.getroot().find("application")
application.attrib.clear()
for activity in application.findall("activity") + application.findall("activity-alias"):
    name = activity.get("{" + ANDROID + "}name", "")
    for intent in list(activity.findall("intent-filter")):
        launcher = any(category.get("{" + ANDROID + "}name", "").endswith("LAUNCHER") for category in intent.findall("category"))
        entry = name in (".MainActivity", ".TvActivity")
        if launcher or entry:
            activity.remove(intent)
    if name == ".MainActivity":
        activity.set("{" + ANDROID + "}launchMode", "singleTop")
for provider in application.findall("provider"):
    if provider.get("{" + ANDROID + "}name") == "androidx.core.content.FileProvider":
        provider.set("{" + ANDROID + "}name", "io.github.aedev.flow.FlowShareProvider")
target = FLOW / "integration/AndroidManifest.xml"
target.parent.mkdir(parents=True, exist_ok=True)
manifest.write(target, encoding="utf-8", xml_declaration=True)
license_target = FLOW / "integration/assets/licenses/flow"
license_target.mkdir(parents=True, exist_ok=True)
(license_target / "LICENSE").write_bytes((FLOW / "License").read_bytes())
(license_target / "upstream-provenance.json").write_bytes((FLOW / "upstream-provenance.json").read_bytes())
print("Prepared Flow manifest and licence assets")
rules = (FLOW / "app/proguard-rules.pro").read_text(encoding="utf-8-sig")
(FLOW / "integration/consumer-rules.pro").write_text("\n".join(line for line in rules.splitlines() if line.strip() != "-dontobfuscate") + "\n", encoding="utf-8")
logo_target = FLOW / "integration/res/drawable/niktube_host_logo.png"
logo_target.parent.mkdir(parents=True, exist_ok=True)
logo_target.write_bytes((ROOT / "app/src/main/res/drawable/niktv_logo_foreground.png").read_bytes())
# Android 13's remembered splash theme belongs to the package, not just Flow's activity.
# Keep every embedded starting-theme variant host-branded, including previously remembered
# styles. Override resources in the host rather than patching upstream theme/controller code.
splash_overrides = ET.Element("resources")
for source_style in ET.parse(FLOW / "app/src/main/res/values/themes.xml").getroot().findall("style"):
    name = source_style.get("name", "")
    if not (name == "Theme.Flow.Starting" or name.startswith("Theme.Flow.Starting.")):
        continue
    attrs = {"name": name}
    if source_style.get("parent"):
        attrs["parent"] = source_style.get("parent")
    style = ET.SubElement(splash_overrides, "style", attrs)
    overridden = {"windowSplashScreenAnimatedIcon", "windowSplashScreenBackground", "windowSplashScreenIconBackgroundColor"}
    for original_item in source_style:
        if original_item.get("name") not in overridden:
            style.append(copy.deepcopy(original_item))
    for key, value in (
        ("windowSplashScreenAnimatedIcon", "@drawable/niktv_logo_foreground"),
        ("windowSplashScreenBackground", "@color/launcher_background"),
        ("windowSplashScreenIconBackgroundColor", "@android:color/transparent"),
    ):
        ET.SubElement(style, "item", {"name": key}).text = value
ET.indent(splash_overrides, space="    ")
splash_file = ROOT / "app/src/main/res/values/embedded_flow_splash.xml"
splash_text = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/prepare-flow.py; host branding for the shared APK splash. -->\n' + ET.tostring(splash_overrides, encoding="unicode") + "\n"
if not splash_file.exists() or splash_file.read_text(encoding="utf-8") != splash_text:
    splash_file.write_text(splash_text, encoding="utf-8")
logo_source = FLOW / "app/src/main/java/io/github/aedev/flow/ui/components/shared/FlowLogo.kt"
logo_source.write_text('''package io.github.aedev.flow.ui.components.shared

import androidx.compose.foundation.Image
import androidx.compose.foundation.layout.aspectRatio
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.res.stringResource
import io.github.aedev.flow.R

@Composable
fun FlowLogo(modifier: Modifier = Modifier) {
    Image(painterResource(R.drawable.niktube_host_logo), stringResource(R.string.app_name), modifier.aspectRatio(1f))
}
''', encoding="utf-8")
header_logo = FLOW / "app/src/main/java/io/github/aedev/flow/ui/screens/home/FlowHeaderLogoIcon.kt"
header_text = header_logo.read_text(encoding="utf-8-sig")
# Keep upstream incognito transitions and long-press behavior, but use the host
# identity for the ordinary Home icon. This is idempotent on repeated builds.
marker = "    val primaryColor = MaterialTheme.colorScheme.primary"
if "painterResource(io.github.aedev.flow.R.drawable.niktube_host_logo)" not in header_text:
    header_text = header_text.replace(marker, '''    if (!isDeepFlowActive) {
        androidx.compose.foundation.Image(
            painter = androidx.compose.ui.res.painterResource(io.github.aedev.flow.R.drawable.niktube_host_logo),
            contentDescription = androidx.compose.ui.res.stringResource(io.github.aedev.flow.R.string.app_name),
            modifier = modifier,
        )
        return
    }
''' + marker)
    header_logo.write_text(header_text, encoding="utf-8")
